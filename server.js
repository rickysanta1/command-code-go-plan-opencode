import http from "node:http";
import { randomUUID } from "node:crypto";
import { pathToFileURL } from "node:url";
import { loadEnv } from "./env.js";
import { resolveModel, toUpstream, readNdjson } from "./upstream.js";
import { createState, applyEvent, toolOf, toToolCalls, toFinishReason, toUsage } from "./stream.js";
import { getApiKey } from "./config.js";

const BASE = "https://api.commandcode.ai";
const MODELS = ["deepseek/deepseek-v4.1-flash", "deepseek/deepseek-v4.1-flash-fast", "deepseek/deepseek-v4-flash", "deepseek/deepseek-v4-pro"];

function send(res, code, obj) {
  if (res.destroyed || res.writableEnded) return;
  res.writeHead(code, { "Content-Type": "application/json" });
  res.end(JSON.stringify(obj));
}

function endSse(res) {
  if (res.destroyed || res.writableEnded) return;
  try {
    res.write("data: [DONE]\n\n");
    res.end();
  } catch {}
}

function chunk(res, id, model, created, delta, finish, usage) {
  if (res.destroyed) return;
  const msg = {
    id,
    object: "chat.completion.chunk",
    created,
    model,
    choices: [{ index: 0, delta, finish_reason: finish || null }],
  };
  if (usage) msg.usage = usage;
  res.write(`data: ${JSON.stringify(msg)}\n\n`);
}

function messageContent(state) {
  const calls = toToolCalls(state);
  return {
    role: "assistant",
    content: state.text,
    ...(state.reasoning ? { reasoning: state.reasoning, reasoning_content: state.reasoning } : {}),
    ...(calls.length ? { tool_calls: calls } : {}),
  };
}

export function startServer(options = {}) {
  loadEnv();
  const VERSION = process.env.CMD_VERSION || "1.79.2";
  const HOST = options.host || "127.0.0.1";
  const PORT = options.port || Number(process.env.PORT || 8787);
  const STATIC_KEY = options.apiKey || process.env.COMMANDCODE_API_KEY || getApiKey() || null;
  const UPSTREAM_TIMEOUT = Math.max(1000, Number(process.env.UPSTREAM_TIMEOUT || 60000));
  const MAX_BODY_BYTES = Math.max(1024, Number(process.env.MAX_BODY_BYTES || 20 * 1024 * 1024));

  async function handleCompletions(req, res, body) {
    const authHeader = req.headers.authorization;
    const headerKey = authHeader ? authHeader.replace(/^Bearer\s+/i, "") : null;
    const key = STATIC_KEY || headerKey;
    if (!key) return send(res, 401, { error: { message: "No API key. Run `commandcode-api-proxy auth login` or set --api-key.", type: "auth_error" } });

    const ac = new AbortController();
    res.on("close", () => {
      if (!res.writableEnded) ac.abort();
    });

    const headerTimer = setTimeout(() => ac.abort(), UPSTREAM_TIMEOUT);
    let r;
    try {
      r = await fetch(`${BASE}/alpha/generate`, {
        method: "POST",
        headers: {
          Authorization: `Bearer ${key}`,
          "Content-Type": "application/json",
          "User-Agent": "cli",
          "x-cli-environment": "production",
          "x-command-code-version": VERSION,
          "x-session-id": randomUUID(),
        },
        body: JSON.stringify(toUpstream(body)),
        signal: ac.signal,
      });
    } catch (err) {
      const timedOut = err && err.name === "AbortError" && !res.destroyed;
      const reason = timedOut
        ? `timed out after ${UPSTREAM_TIMEOUT}ms waiting for upstream`
        : (err && err.message) || String(err);
      return send(res, 502, { error: { message: "Upstream request failed: " + reason, type: "upstream_error" } });
    } finally {
      clearTimeout(headerTimer);
    }

    if (!r.ok) {
      const text = await r.text().catch(() => "");
      return send(res, r.status, { error: { message: text, type: "upstream_error" } });
    }

    const model = body.model || "deepseek-v4.1-flash";
    const id = "chatcmpl-" + randomUUID().slice(0, 8);
    const created = Math.floor(Date.now() / 1000);
    const finish = toFinishReason;

    if (!body.stream) {
      const state = createState();
      try {
        for await (const e of readNdjson(r)) applyEvent(state, e);
      } catch (err) {
        state.error = err;
      }
      const msg = messageContent(state);
      if (!msg.content && (!msg.tool_calls || msg.tool_calls.length === 0)) {
        if (state.error) msg.content = "Error from upstream: " + (state.error.message || JSON.stringify(state.error));
        else if (state.reasoning) msg.content = state.reasoning;
        else msg.content = "No response generated by model.";
      }
      return send(res, 200, {
        id,
        object: "chat.completion",
        created,
        model,
        choices: [{ index: 0, message: msg, finish_reason: finish(state) }],
        usage: toUsage(state.usage),
      });
    }

    res.writeHead(200, { "Content-Type": "text/event-stream", "Cache-Control": "no-cache", Connection: "keep-alive" });
    chunk(res, id, model, created, { role: "assistant", content: "" });

    const state = createState();
    const sentTools = new Set();
    let reasoningOpen = false;

    try {
      for await (const e of readNdjson(r)) {
        applyEvent(state, e);
        if (e.type === "reasoning-delta" && e.text) {
          reasoningOpen = true;
          chunk(res, id, model, created, { reasoning: e.text, reasoning_content: e.text });
        } else if (e.type === "text-delta" && e.text) {
          chunk(res, id, model, created, { content: e.text });
        } else if (e.type === "tool-call") {
          const t = toolOf(state, e.toolCallId);
          if (t) {
            sentTools.add(t.id);
            chunk(res, id, model, created, { tool_calls: [{ index: t.index, id: t.id, type: "function", function: { name: t.name, arguments: t.args } }] });
          }
        }
      }
    } catch (err) {
      state.error = err;
    }

    for (const t of state.tools) {
      if (!sentTools.has(t.id)) {
        sentTools.add(t.id);
        chunk(res, id, model, created, { tool_calls: [{ index: t.index, id: t.id, type: "function", function: { name: t.name, arguments: t.args } }] });
      }
    }

    if (!state.text && state.tools.length === 0) {
      if (state.error) {
        chunk(res, id, model, created, { content: "Error from upstream: " + (state.error.message || JSON.stringify(state.error)) });
      } else if (state.reasoning) {
        chunk(res, id, model, created, { content: state.reasoning });
      } else {
        chunk(res, id, model, created, { content: "No response generated by model." });
      }
    }

    if (reasoningOpen) chunk(res, id, model, created, {});
    chunk(res, id, model, created, {}, finish(state), toUsage(state.usage));
    endSse(res);
  }

  const server = http.createServer((req, res) => {
    if (req.method === "GET" && req.url === "/health") return send(res, 200, { ok: true, models: MODELS.length });
    if (req.method === "GET" && req.url === "/v1/models") {
      return send(res, 200, { object: "list", data: MODELS.map((id) => ({ id, object: "model", owned_by: "commandcode" })) });
    }
    if (req.method === "POST" && (req.url === "/v1/chat/completions" || req.url === "/chat/completions")) {
      const chunks = [];
      let size = 0;
      let overflow = false;
      req.on("data", (c) => {
        if (overflow) return;
        size += c.length;
        if (size > MAX_BODY_BYTES) {
          overflow = true;
          chunks.length = 0;
          return;
        }
        chunks.push(c);
      });
      req.on("end", () => {
        if (overflow) return send(res, 413, { error: { message: "Request body too large", type: "invalid_request_error" } });
        let body;
        try {
          body = JSON.parse(Buffer.concat(chunks).toString("utf8") || "{}");
        } catch {
          return send(res, 400, { error: { message: "Invalid JSON in request body", type: "invalid_request_error" } });
        }
        handleCompletions(req, res, body).catch((e) => {
          if (res.headersSent) return endSse(res);
          send(res, 500, { error: { message: String(e) } });
        });
      });
      return;
    }
    send(res, 404, { error: "not found" });
  });

  const CONNECTIONS = new Set();
  server.on("connection", (conn) => {
    CONNECTIONS.add(conn);
    conn.on("close", () => CONNECTIONS.delete(conn));
  });

  let shuttingDown = false;
  function shutdown(signal) {
    if (shuttingDown) return process.exit(0);
    shuttingDown = true;
    console.log(`\n${signal} received: closing server, waiting for active requests...`);
    server.closeIdleConnections();
    server.close(() => process.exit(0));
    setTimeout(() => process.exit(0), 10000).unref();
  }
  process.on("SIGINT", () => shutdown("SIGINT"));
  process.on("SIGTERM", () => shutdown("SIGTERM"));

  server.listen(PORT, HOST, () => {
    const log = options.log || console.log;
    log(`proxy on http://${HOST === "0.0.0.0" || HOST === "::" ? "127.0.0.1" : HOST}:${PORT} model=${resolveModel("deepseek/deepseek-v4.1-flash")} models=${MODELS.length} key=${STATIC_KEY ? "saved/env/flag" : "per-request header only"}`);
  });

  return server;
}

// `node server.js` still works like before.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  startServer();
}
